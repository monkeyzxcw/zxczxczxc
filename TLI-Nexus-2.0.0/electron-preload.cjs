const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('nexus', {
  getState: () => ipcRenderer.invoke('live:get'),
  chooseLog: () => ipcRenderer.invoke('live:choose-log'),
  useAutoLog: () => ipcRenderer.invoke('live:auto-log'),
  refreshCharacterIntel: () => ipcRenderer.invoke('live:refresh-character'),
  getCharacterReport: (profileId) => ipcRenderer.invoke('character:report', profileId),
  captureCharacterSnapshot: (profileId) => ipcRenderer.invoke('character:capture-snapshot', profileId),
  compareCharacterSnapshots: (previous, current) => ipcRenderer.invoke('character:compare-snapshots', previous, current),
  exportCharacterDiagnostics: (profileId) => ipcRenderer.invoke('character:export-diagnostics', profileId),
  loadData: () => ipcRenderer.invoke('app:load-data'),
  saveData: (data) => ipcRenderer.invoke('app:save-data', data),
  updateSettings: (settings) => ipcRenderer.invoke('app:update-settings', settings),
  copyText: (text) => ipcRenderer.invoke('app:copy', text),
  showDashboard: () => ipcRenderer.invoke('app:show-dashboard'),
  showOverlay: () => ipcRenderer.invoke('app:show-overlay'),
  openDataFolder: () => ipcRenderer.invoke('app:open-data-folder'),
  setOverlayMode: (mode) => ipcRenderer.invoke('app:set-overlay-mode', mode),
  setClickThrough: (value) => ipcRenderer.invoke('app:set-clickthrough', value),
  exportBackup: () => ipcRenderer.invoke('app:export'),
  importBackup: () => ipcRenderer.invoke('app:import'),
  searchItems: (query) => ipcRenderer.invoke('items:search', query),
  getItemIcon: (id) => ipcRenderer.invoke('items:icon', id),
  getPriceHistory: (id, days = 30, seasonId = undefined) => ipcRenderer.invoke('prices:history', id, days, seasonId),
  analyzeBuild: (build) => ipcRenderer.invoke('build:analyze', build),
  analyzeEquipment: (items, priorities) => ipcRenderer.invoke('equipment:analyze', items, priorities),
  compareEquipment: (left, right, priorities) => ipcRenderer.invoke('equipment:compare', left, right, priorities),
  analyzeFarming: (sessions, options) => ipcRenderer.invoke('farm:analyze', sessions, options),
  compareBuilds: (left, right) => ipcRenderer.invoke('build:compare', left, right),
  encodeBuild: (build) => ipcRenderer.invoke('build:encode', build),
  decodeBuild: (code) => ipcRenderer.invoke('build:decode', code),
  getBuildStatFields: () => ipcRenderer.invoke('build:stat-fields'),
  openExternal: (url) => ipcRenderer.invoke('app:open-external', url),
  onState: (fn) => { const handler = (_e, state) => fn(state); ipcRenderer.on('live:update', handler); return () => ipcRenderer.removeListener('live:update', handler); },
  onSettings: (fn) => { const handler = (_e, settings) => fn(settings); ipcRenderer.on('app:settings', handler); return () => ipcRenderer.removeListener('app:settings', handler); },
  close: () => ipcRenderer.send('overlay:close'),
  toggleMode: () => ipcRenderer.send('overlay:toggle-mode'),
  openDashboardWindow: () => ipcRenderer.send('overlay:open-dashboard'),
  toggleClickThrough: () => ipcRenderer.invoke('app:toggle-clickthrough'),
  togglePin: (enabled) => ipcRenderer.invoke('app:set-always-on-top', enabled),
});
